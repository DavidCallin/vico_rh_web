<?php

namespace App\Http\Controllers\Api;

use App\Http\Controllers\Controller;
use App\Http\Requests\StoreContractRequest;
use App\Http\Requests\UpdateContractRequest;
use App\Http\Resources\ContractResource;
use App\Models\Contract;
use Barryvdh\DomPDF\Facade\Pdf;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Storage;

class ContractController extends Controller
{
    /**
     * Liste des contrats
     */
    public function index(Request $request)
    {
        $query = Contract::with('employee.position.department');

        // Filtre par type de contrat
        if ($request->has('contract_type')) {
            $query->where('contract_type', $request->contract_type);
        }

        // Filtre par employé
        if ($request->has('employee_id')) {
            $query->where('employee_id', $request->employee_id);
        }

        // Filtre : contrats actifs uniquement
        if ($request->boolean('active_only')) {
            $query->where(function ($q) {
                $q->whereNull('end_date')
                  ->orWhere('end_date', '>', now());
            });
        }

        $contracts = $query->orderBy('start_date', 'desc')->paginate(15);

        return ContractResource::collection($contracts);
    }

    /**
     * Créer un contrat
     */
    public function store(StoreContractRequest $request)
    {
        // Upload du PDF si fourni
        $pdfPath = null;
        if ($request->hasFile('pdf')) {
            $pdfPath = $request->file('pdf')->store('contracts', 'public');
        }

        $contract = Contract::create([
            'employee_id' => $request->employee_id,
            'contract_type' => $request->contract_type,
            'start_date' => $request->start_date,
            'end_date' => $request->end_date,
            'base_salary' => $request->base_salary,
            'pdf_path' => $pdfPath,
        ]);

        // 🎯 GÉNÉRATION AUTOMATIQUE DU PDF
        $pdf = Pdf::loadView('pdf.contract', [
            'contract' => $contract->load('employee')
        ]);

        $fileName = 'contrats/contrat_' . $contract->employee->matricule . '_' . date('Y-m-d') . '.pdf';
        
        // Sauvegarder le PDF dans le storage public
        Storage::disk('public')->put($fileName, $pdf->output());

        // Mettre à jour le chemin du fichier dans la base de données
        $contract->update(['file_path' => $fileName]);

        return response()->json([
            'message' => 'Contrat créé et PDF généré avec succès',
            'data' => $contract->fresh()->load('employee')
        ]);
    }

    /**
     * Afficher un contrat
     */
    public function show(Contract $contract)
    {
        $contract->load('employee.position.department');
        return new ContractResource($contract);
    }

    /**
     * Mettre à jour un contrat
     */
        public function update(UpdateContractRequest $request, Contract $contract)
    {
        // 1. Récupérer les données validées
        $data = $request->validated();

        // 2. Gestion du fichier uploadé (si l'utilisateur en fournit un nouveau)
        if ($request->hasFile('file')) {
            // Supprimer l'ancien fichier s'il existe
            if ($contract->file_path) {
                Storage::disk('public')->delete($contract->file_path);
            }
            $data['file_path'] = $request->file('file')->store('contracts', 'public');
        }

        // 3. Mettre à jour le contrat en base
        $contract->update($data);

        // 4. 🎯 SUPPRIMER L'ANCIEN PDF GÉNÉRÉ AUTOMATIQUEMENT
        // (car les données ont changé, le PDF n'est plus à jour)
        $oldAutoGeneratedPath = 'contrats/contrat_' . $contract->employee->matricule . '_*.pdf';
        $files = Storage::disk('public')->files('contrats');
        foreach ($files as $file) {
            // Supprimer tous les anciens PDF de cet employé
            if (str_starts_with($file, 'contrats/contrat_' . $contract->employee->matricule . '_') 
                && str_ends_with($file, '.pdf')) {
                Storage::disk('public')->delete($file);
            }
        }

        // 5. 🎯 GÉNÉRER UN NOUVEAU PDF AVEC LES NOUVELLES DONNÉES
        $pdf = Pdf::loadView('pdf.contract', [
            'contract' => $contract->load('employee')
        ]);

        $fileName = 'contrats/contrat_' . $contract->employee->matricule . '_' . date('Y-m-d') . '.pdf';
        
        // Sauvegarder le nouveau PDF
        Storage::disk('public')->put($fileName, $pdf->output());

        // 6. Mettre à jour le chemin du fichier dans la base de données
        $contract->update(['file_path' => $fileName]);

        // 7. Retourner la réponse
        return response()->json([
            'message' => 'Contrat mis à jour et PDF régénéré avec succès',
            'data' => $contract->fresh()->load('employee')
        ]);
    }

    /**
     * Supprimer un contrat
     */
    public function destroy(Contract $contract)
    {
        // Supprimer le PDF s'il existe
        if ($contract->pdf_path) {
            Storage::disk('public')->delete($contract->pdf_path);
        }

        $contract->delete();

        return response()->noContent();
    }
}